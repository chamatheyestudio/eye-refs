  viewLink: call('projects:viewLink'),
  share: call('projects:share'),
  members: call('projects:members'),
  invite: call('projects:invite'),
  decide: call('projects:decide'),
  removeMember: call('projects:removeMember'),
  join: call('projects:join'),
  packProject: call('projects:pack'),
  reveal: call('projects:reveal'),
  write: call('board:write'),
  flush: call('board:flush'),
  importPaths: call('media:importPaths'),
  importBytes: call('media:importBytes'),
  importUrl: call('media:importUrl'),
  readClipboard: call('clipboard:read'),
